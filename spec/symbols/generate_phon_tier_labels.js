#!/usr/bin/env node

// Structured Phon labels share an owner with their custom-label exclusions.
const fs = require('node:fs');
const path = require('node:path');
const { rustLiteral, rustVariant, rustfmt, writeGenerated } = require('./registry.js');
const repoRoot = path.resolve(__dirname, '..', '..');
const labels = JSON.parse(fs.readFileSync(path.join(__dirname, 'phon_tier_labels.json'), 'utf8'));
if (!labels || Array.isArray(labels) || typeof labels !== 'object' || !Object.keys(labels).length) {
  throw new Error('Phon tier labels must be a nonempty object');
}
const seen = new Set();
for (const [kind, spellings] of Object.entries(labels)) {
  if (!kind || /[^a-z]/.test(kind) || !Array.isArray(spellings) || !spellings.length) {
    throw new Error(`Invalid Phon tier label group: ${kind}`);
  }
  for (const spelling of spellings) {
    if (typeof spelling !== 'string' || !spelling || /[^a-z]/.test(spelling) || seen.has(spelling)) {
      throw new Error(`Invalid or duplicate Phon tier label: ${spelling}`);
    }
    seen.add(spelling);
  }
}
const reserved = [...seen].filter(label => label.startsWith('x'));
const variants = Object.keys(labels).map(kind =>
  `/// Structured ${kind} tier.\n${rustVariant(kind)},`).join('\n');
const recognition = Object.entries(labels).map(([kind, spellings]) =>
  `${spellings.map(rustLiteral).join(' | ')} => Some(Self::${rustVariant(kind)}),`).join('\n');
writeGenerated(repoRoot, path.join(repoRoot, 'grammar/src/generated_phon_tier_labels.js'),
  `// @generated by spec/symbols/generate_phon_tier_labels.js\n// DO NOT EDIT MANUALLY.\nexport const PHON_TIER_PREFIXES = ${JSON.stringify(Object.fromEntries(
    Object.entries(labels).map(([kind, spellings]) => [kind, spellings.map(label => `%${label}`)]),
  ), null, 2)};\n`);
writeGenerated(repoRoot, path.join(repoRoot, 'crates/talkbank-model/src/generated/phon_tier_labels.rs'),
  rustfmt(`// @generated by spec/symbols/generate_phon_tier_labels.js
// DO NOT EDIT MANUALLY.
/// The structured Phon tier families and their admitted label aliases.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PhonTierKind { ${variants} }
impl PhonTierKind {
    /// Recognize a full label without its percent sign.
    pub fn from_label(label: &str) -> Option<Self> {
        match label { ${recognition} _ => None }
    }
}
/// Structured labels excluded from the custom-tier namespace.
pub const RESERVED_CUSTOM_TIER_LABELS: &[&str] = &[${reserved.map(rustLiteral).join(', ')}];
`));
