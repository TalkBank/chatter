#!/usr/bin/env node

// Emits the Rust character-set constants from the symbol registry.
//
// The emission order is `Object.keys(registry.categories)`, which registry.js
// builds. An earlier cut restated that order here as a const, so the order was
// asserted in two files that had to agree, which is the mirror this registry
// exists to delete.

const path = require('node:path');
const { loadRegistry, rustLiteral, rustCharPattern, rustfmt, writeGenerated } = require('./registry.js');

// Characters are admitted Unicode scalars before reaching this emitter.
function jsonSchemaClassBody(symbols) {
  return symbols.map(character => {
    const codepoint = character.codePointAt(0);
    return codepoint <= 0xffff ? `\\u${codepoint.toString(16).padStart(4, '0')}` : character;
  }).join('');
}

function renderRust(categories) {
  const rows = Object.entries(categories).map(
    ([key, values]) =>
      `pub const ${key.toUpperCase()}: &[&str] = &[${values.map(rustLiteral).join(', ')}];`,
  );
  const restForbidden = [...new Set([
    ...categories.word_segment_forbidden_rest_symbols,
    ...categories.word_segment_forbidden_common_symbols,
    ...categories.word_attached_symbols,
    ...categories.paired_stretch_symbols,
  ])];
  rows.push(`/// Registry character-class membership for continuation of a word segment.
/// Source validity and nonempty segment admission belong to the parser.
#[inline]
pub fn is_word_segment_rest_char(character: char) -> bool {
    !matches!(character, ${restForbidden.map(rustCharPattern).join(' | ')})
}`);
  const eventForbidden = [...new Set([
    ...categories.event_segment_forbidden_symbols,
    ...categories.event_segment_forbidden_common_symbols,
    ...categories.word_attached_symbols,
    ...categories.paired_stretch_symbols,
    '\0',
  ])];
  rows.push(`/// Registry character-class membership for an event description.
/// NUL is reserved for physical end of input by the native lexer.
#[inline]
pub fn is_event_segment_char(character: char) -> bool {
    !matches!(character, ${eventForbidden.map(rustCharPattern).join(' | ')})
}`);
  // JSON Schema searches this class anywhere in the payload, avoiding the
  // special before-final-newline meaning of a regex end anchor.
  const forbiddenPattern = `[${jsonSchemaClassBody(eventForbidden)}]`;
  rows.push(`/// JSON Schema pattern for forbidden event-description characters.
pub const EVENT_SEGMENT_FORBIDDEN_PATTERN: &str = ${rustLiteral(forbiddenPattern)};`);
  const scopeSymbols = categories.scoped_marker_label_symbols;
  rows.push(`/// Character admission shared by long-event and nonvocal labels.
#[inline]
pub fn is_scoped_marker_label_char(character: char) -> bool {
    matches!(character, ${scopeSymbols.map(rustCharPattern).join(' | ')})
}`);
  const scopeForbidden = `[^${jsonSchemaClassBody(scopeSymbols)}]`;
  rows.push(`/// JSON Schema pattern detecting any non-label character.
pub const SCOPED_MARKER_LABEL_FORBIDDEN_PATTERN: &str = ${rustLiteral(scopeForbidden)};`);
  return rustfmt(
    `// @generated by spec/symbols/generate_rust_symbol_sets.js\n// DO NOT EDIT MANUALLY.\n\n${rows.join('\n')}\n`,
  );
}

function main() {
  const { repoRoot, categories } = loadRegistry();
  const content = renderRust(categories);
  for (const output of [
    path.join(repoRoot, 'crates', 'talkbank-model', 'src', 'generated', 'symbol_sets.rs'),
    path.join(repoRoot, 'spec', 'tools', 'src', 'generated', 'symbol_sets.rs'),
  ]) {
    writeGenerated(repoRoot, output, content);
  }
}

main();
