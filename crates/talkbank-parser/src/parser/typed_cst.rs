/// A kind slot (a child taken by its kind, never `Unexpected`) whatever its
/// `Missing` payload `M` is.
///
/// The generator spells that payload two ways: `KindMissing<T>` at a slot
/// whose kind can be MISSING, and `NarrowedMissing<K, KindMissing<T>>` at a
/// slot the compiled grammar proves never MISSING, which holds the placeholder
/// under the `Broad` kind proof and is uninhabited under `KindAdmitted`. A
/// helper several kinds of position share is generic over `M` and asks of it
/// only what it reads: the projection `view()` needs (`SourceRecovery` or
/// `RecoveryNode`) when it merely matches `Missing(_)`, a source view of the
/// expected kind when it reads the placeholder's text. A helper whose
/// every caller holds a narrowed admitted reading can name
/// `NonMissingKindSlot` instead and omit its uninhabited `Missing` arm.
/// Ordinary `KindSlot` positions retain their typed missing placeholder.
pub(crate) type AnyKindSlot<T, M, E, A = NoChild> = NodeSlot<T, M, E, Never, A>;

/// [`AnyKindSlot`] for a retained repeat element or a present optional: never
/// `Absent`.
pub(crate) type AnySelectedKindSlot<T, M, E> = NodeSlot<T, M, E, Never, Never>;

/// A required lexical field still permits a native Missing placeholder. Its
/// Error and Absent states are excluded by the parent's compiled rule.
pub(in crate::parser) type RequiredLexicalField<'value, 'tree, 'source, T> = SourceField<
    'value,
    'tree,
    'source,
    AnyKindSlot<
        T,
        crate::generated_traversal::KindMissing<T>,
        crate::generated_traversal::PresenceError<
            crate::generated_traversal::RequiredPresence,
            tree_sitter::Node<'tree>,
        >,
        Never,
    >,
>;

/// Admit the statically linked CHAT producer once, retaining failures as tool
/// faults. No consumer may substitute a kind-name or source-read assertion.
pub(in crate::parser) fn canonical_grammar() -> Result<&'static CanonicalLanguage, CstFailure> {
    static GRAMMAR: std::sync::OnceLock<Result<CanonicalLanguage, GrammarBindingError>> =
        std::sync::OnceLock::new();
    GRAMMAR
        .get_or_init(|| {
            // SAFETY: the bridge is generated by TSGU and compiled by the grammar
            // crate against its own parser header. All exports have static
            // lifetime; no dynamic library can disappear while admission is held.
            // The locked Tree-sitter 0.27.1 runtime is the engine reviewed by
            // this producer; ABI compatibility alone is not sufficient.
            unsafe {
                CompiledLanguage::from_bridge(
                    tree_sitter_talkbank::LANGUAGE.into(),
                    tree_sitter_talkbank::LANGUAGE_METADATA_BRIDGE,
                    RequiredPresenceBridge {
                        create: tree_sitter_talkbank::REQUIRED_GRAPH_NEW,
                        destroy: tree_sitter_talkbank::REQUIRED_GRAPH_DROP,
                        check: tree_sitter_talkbank::REQUIRED_RULE,
                        prefix: tree_sitter_talkbank::REQUIRED_PREFIX,
                    },
                )
            }
            .admit_generated()
        })
        .as_ref()
        .map_err(|error| CstFailure::Grammar(*error))
}

/// Per-rule ordinary-header evidence, cached independently of other rule shapes.
pub(in crate::parser) fn participants_rule()
-> Result<&'static RequiredRule<ParticipantsHeaderChildrenRule>, CstFailure> {
    <ParticipantsHeaderChildrenRule as envelope::EnvelopeRule>::admitted()
}

/// Per-rule ordinary-main-tier evidence; source trees are never scanned for admission.
pub(in crate::parser) fn main_tier_rule()
-> Result<&'static RequiredRule<MainTierChildrenRule>, CstFailure> {
    static RULE: std::sync::OnceLock<Result<RequiredRule<MainTierChildrenRule>, CstFailure>> =
        std::sync::OnceLock::new();
    RULE.get_or_init(|| canonical_grammar()?.required_rule().map_err(Into::into))
        .as_ref()
        .map_err(|fault| *fault)
}

/// Admission failures, distinct from source recovery evidence. Broad extraction
/// is total; these errors identify broken source or compiled-grammar evidence.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
pub enum CstFailure {
    /// A node could not be associated with its producing source.
    #[error(transparent)]
    Binding(#[from] SourceBindingError),
    /// The compiled grammar does not match the generated narrowing evidence.
    #[error(transparent)]
    Grammar(#[from] GrammarBindingError),
    /// A node contradicts the admitted language or kind proof.
    #[error(transparent)]
    Admission(#[from] AdmittedRefusal),
    /// A `Missing` or `Error` slot inside a tier admitted as recovery-free
    /// ([`crate::parser::tier_parsers::admission::HealthyTier`]): the walk's
    /// reading contradicts tree-sitter's own `has_error` flag, so it is a
    /// producer fault, never a CHAT invalidity.
    #[error("recovery node inside a tier admitted as recovery-free while matching `{rule}`")]
    RecoveryInsideHealthyTier {
        /// The grammar rule whose shape the walk was matching.
        rule: &'static str,
    },
    /// The reconstruction walk left a required position with no child at
    /// all. Only a generated shape that disagrees with the real child list
    /// can produce that (the grammar has no fail-closed partials, and the
    /// slot-state census of 2026-09-09 saw it at no required position), so
    /// it is a generator or grammar fault and never a CHAT invalidity: the
    /// consumer reports it here instead of inventing a CHAT diagnostic for
    /// content that was never read.
    #[error("required position `{position}` of `{rule}` has no child")]
    AbsentRequiredPosition {
        /// The grammar rule whose shape the walk matched.
        rule: &'static str,
        /// The position the walk left empty.
        position: GeneratedPosition,
    },
}

/// A generated carrier and field, spelled as the slot-state census spells
/// them (`ParticipantChildren.code`, `ParticipantsContentsChild1Children.child_2`).
/// A newtype so a fault cannot be built with its rule and position swapped,
/// which two bare `&'static str` fields would let compile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GeneratedPosition(&'static str);

impl GeneratedPosition {
    /// Name a position; only parser code names them, from the generated
    /// carrier and field it is matching on.
    pub(in crate::parser) const fn new(name: &'static str) -> Self {
        Self(name)
    }
}

impl std::fmt::Display for GeneratedPosition {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.0)
    }
}

/// Evidence that a producer failure has already been sent to the owning sink.
/// Constructed only after reporting the fault; callers stop lowering instead
/// of inventing replacement fields or emitting a second CHAT diagnostic.
pub(in crate::parser) struct ReportedCstFailure;

/// Extraction under the canonical grammar's admitted kind proof.
///
/// Every parser that reads admitted children binds the canonical grammar,
/// extracts under `KindAdmitted` and converts the proof's refusal; this is
/// that one route, so a grammar-binding fault and a refusal of a tree that
/// contradicts the proof both arrive as one `CstFailure`.
pub(in crate::parser) trait ExtractCanonical<'tree, 'source, W: Extract<'tree>> {
    /// The admitted children, with their source owner.
    ///
    /// # Errors
    /// The grammar-binding fault, or the admitted proof's refusal.
    fn extract_canonical(
        self,
    ) -> Result<SourceChildren<'tree, 'source, W::Children<KindAdmitted>>, CstFailure>;
}

impl<'tree, 'source, W: Extract<'tree> + SourceBoundKind<'tree>> ExtractCanonical<'tree, 'source, W>
    for SourceBound<'tree, 'source, W>
{
    fn extract_canonical(
        self,
    ) -> Result<SourceChildren<'tree, 'source, W::Children<KindAdmitted>>, CstFailure> {
        self.extract_admitted(canonical_grammar()?)
            .map_err(Into::into)
    }
}

/// Admit extracted fields or report the producer fault exactly once.
pub(in crate::parser) fn report_admission<T>(
    result: Result<T, CstFailure>,
    node: tree_sitter::Node<'_>,
    source: &str,
    errors: &impl ErrorSink,
) -> Result<T, ReportedCstFailure> {
    result.map_err(|fault| {
        report_cst_failure(node, source, fault, errors);
        ReportedCstFailure
    })
}

/// Report producer failure at the boundary that still owns the source node.
pub(in crate::parser) fn report_cst_failure(
    node: tree_sitter::Node<'_>,
    source: &str,
    error: impl Into<CstFailure>,
    errors: &impl ErrorSink,
) {
    errors.report(cst_failure_diagnostic(node, source, error));
}

/// Build producer-failure evidence for non-streaming admission boundaries.
pub(in crate::parser) fn cst_failure_diagnostic(
    node: tree_sitter::Node<'_>,
    source: &str,
    error: impl Into<CstFailure>,
) -> ParseError {
    let error = error.into();
    ParseError::new(
        ErrorCode::InternalError,
        Severity::Error,
        DiagnosticLocation::new(span_of(node)),
        ErrorContext::new(source, span_of(node), node.kind()),
        error.to_string(),
    )
}

/// Admit an associated typed field's own range; source identity is already
/// guaranteed by the generated projection. No independent text can be supplied.
pub(in crate::parser) fn read_source_field<'tree, 'source, T: SourceBoundKind<'tree>>(
    field: SourceField<'_, 'tree, 'source, T>,
    errors: &impl ErrorSink,
) -> Option<SourceBound<'tree, 'source, T>> {
    match field.read() {
        Ok(bound) => Some(bound),
        Err(error) => {
            report_cst_failure(field.raw_node(), field.source(), error, errors);
            None
        }
    }
}

#[cfg(test)]
#[allow(clippy::expect_used)]
mod tests {
    use super::*;
    use crate::TreeSitterParser;
    use talkbank_model::ErrorCollector;

    #[test]
    fn admission_failure_reports_once_without_a_source_invalidity_verdict() {
        let source = include_str!("../../../../corpus/reference/tiers/mor-gra.cha");
        let parser = TreeSitterParser::new().expect("grammar");
        let parsed = parser
            .parse_source_incremental(source, None)
            .expect("parse");
        for refusal in [
            AdmittedRefusal::ForeignLanguage,
            AdmittedRefusal::WrongRequiredParent,
            AdmittedRefusal::ContradictedPresenceProof,
        ] {
            let sink = ErrorCollector::new();
            let result =
                report_admission::<()>(Err(refusal.into()), parsed.root_node(), source, &sink);
            assert!(result.is_err());
            let diagnostics = sink.into_vec();
            assert_eq!(diagnostics.len(), 1);
            assert_eq!(diagnostics[0].code, ErrorCode::InternalError);
            assert!(talkbank_model::CompletedDiagnostics::admit(diagnostics).is_err());
        }

        // A generated leaf span can fail admission without a CHAT validity
        // verdict. Inject the boundary fault, not a fabricated malformed CST.
        let sink = ErrorCollector::new();
        report_cst_failure(
            parsed.root_node(),
            source,
            SourceBindingError::InvalidRange,
            &sink,
        );
        let diagnostics = sink.into_vec();
        assert_eq!(diagnostics.len(), 1);
        assert_eq!(diagnostics[0].code, ErrorCode::InternalError);
        assert!(talkbank_model::CompletedDiagnostics::admit(diagnostics).is_err());
    }
}
